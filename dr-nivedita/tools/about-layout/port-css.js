// Builds public/css/about.css: the component CSS of the dadumedicalcentre.com About pages
// (About Clinic acx-*, Dr. Nivedita Dadu dr-nandani-/nbd-/nwc-/.../dnv-/rv-, Technology tech-*),
// copied from the reference sources in ./ref (styled-jsx scope classes removed), on this
// site's peach tokens. Loaded only by the 5 About pages (config/pages.js: css).
// Usage: node port-css.js
const fs = require('fs'), path = require('path');
const REF = path.join(__dirname, 'ref');
const OUT = 'D:/DMC website rework/dr-nivedita/local/website/public/css/about.css';

function rules(css, keep) {
  const out = [], n = css.length;
  const end = s => { let d = 0; for (let j = s; j < n; j++) { if (css[j] === '{') d++; else if (css[j] === '}' && --d === 0) return j + 1; } return n; };
  for (let i = 0; i < n;) {
    const b = css.indexOf('{', i); if (b < 0) break;
    const e = end(b), body = css.slice(i, e).trim();
    if (keep.test(body)) out.push(body);
    i = e;
  }
  return out;
}
const unscope = s => s.replace(/\.jsx-[a-f0-9]+/g, '');

const ABOUT = /\.acx-/;
const DOC = /\.(dr-nandani-|nbd-|nwc-|njc-|nsp-|sfd-|nso-|nex-|dnp-|nhl-|dnf-|dnv-|rv-|nandani-)|@keyframes (nbd|nwc|njc|nsp|sfd|nso|nex|dnp|nhl|dnf|dnv|rv|drNandani|nandani)/i;
const TECH = /\.tech-|@keyframes tech/;
const parts = [
  ['About Clinic', rules(fs.readFileSync(path.join(REF, 'about-clinic.chunk.css'), 'utf8'), ABOUT)],
  ['Dr. Nivedita Dadu', rules(unscope(fs.readFileSync(path.join(REF, 'dr-nivedita-dadu.inline.css'), 'utf8')), DOC)],
  ['Technology', rules(unscope(fs.readFileSync(path.join(REF, 'technology.inline.css'), 'utf8')), TECH)],
];

// reference brand colours -> this site's tokens (the reference coral #e28a65 is our --primary)
const colour = s => s
  .replace(/#e28a65([0-9a-f]{2})\b/gi, (m, a) => `color-mix(in srgb,var(--primary) ${Math.round(parseInt(a, 16) / 2.55)}%,transparent)`)
  .replace(/#e28a65\b/gi, 'var(--primary)')
  .replace(/#a8532f\b/gi, 'var(--primary-deep)')
  .replace(/rgba?\(\s*226\s*,\s*138\s*,\s*101\s*,\s*([\d.]+)\s*\)/g, (m, a) => `color-mix(in srgb,var(--primary) ${Math.round(a * 100)}%,transparent)`)
  .replace(/#([0-9a-f]{6})([0-9a-f]{2})?\b/gi, (m, rgb, a) => {
    // the reference's other orange/peach shades (hue 5-28deg) -> nearest token by lightness;
    // gold accents (hue > 28) and near-black shadows stay as they are
    const [r, g, b] = [0, 2, 4].map(i => parseInt(rgb.slice(i, i + 2), 16) / 255);
    const mx = Math.max(r, g, b), mn = Math.min(r, g, b), l = (mx + mn) / 2, d = mx - mn;
    if (!d || l < 0.3) return m;
    const s = d / (1 - Math.abs(2 * l - 1));
    let h = mx === r ? ((g - b) / d) % 6 : mx === g ? (b - r) / d + 2 : (r - g) / d + 4; h = (h * 60 + 360) % 360;
    if (h < 5 || h > 28 || s < 0.3) return m;
    const tok = l > 0.965 ? '--mist' : l > 0.935 ? '--tint' : l > 0.9 ? '--panel' : l > 0.8 ? '--border' : l > 0.55 ? '--primary' : '--primary-deep';
    return a ? `color-mix(in srgb,var(${tok}) ${Math.round(parseInt(a, 16) / 2.55)}%,transparent)` : `var(${tok})`;
  });

const tokens = `/* reference variables on this site's peach tokens */
:root{
  --clr-peach:var(--primary);--clr-peach-deep:var(--primary-deep);--clr-peach-border:var(--border);
  --clr-peach-light:var(--panel);--clr-peach-tint:var(--tint);--clr-peach-mist:var(--mist);
  --clr-blue:var(--primary-deep);--clr-blue-deep:var(--primary-deep);--clr-blue-border:var(--border);--clr-blue-mist:var(--mist);--clr-blue-tint:var(--tint);   /* rendered peach on the reference */
  --acx-ink:#222b3b;--acx-muted:#667085;
}`;
const css = `/* GENERATED by tools/about-layout/port-css.js - edit the tool or about-extra.css, not this file. */\n${tokens}\n` +
  parts.map(([name, r]) => `\n/* ===== ${name} (${r.length} rules) ===== */\n` + colour(r.join('\n'))).join('\n') + '\n';
fs.writeFileSync(OUT, css + fs.readFileSync(path.join(__dirname, 'about-extra.css'), 'utf8'));
console.log(parts.map(([n, r]) => `${n}: ${r.length}`).join(', '), '->', (css.length / 1024).toFixed(1) + ' KB');
